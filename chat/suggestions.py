MAX_SUGGESTIONS = 3

# ⚠️ و کفِ دوتا: یک دکمهٔ تنها وسطِ صفحه شبیهِ دستور است نه پیشنهاد.
MIN_SUGGESTIONS = 2


def build_suggestions(tools_used, context=None):
    """تا سه سوالِ بعدی، بر پایهٔ ابزارهای اجراشده.

    ترتیب از خاص به عام است: اول سوال‌های ابزارهایی که واقعاً اجرا شدند (از آخری
    به اولی، چون مسیرِ گفتگو از کلی به جزئی می‌رود)، بعد اگر جا ماند با
    سوال‌های عمومی پر می‌شود.

    بدونِ ابزار، پیشنهادی هم نیست: اگر دستیار فقط سلام کرده یا نتوانسته جواب
    بدهد، ردیفِ سوال‌های چسبانده به آن مزاحمت است نه کمک.

    خروجی فهرستی از **رشته** است — همان متنی که با کلیک به‌جای کاربر فرستاده
    می‌شود. `context` اینجا استفاده نمی‌شود ولی در امضا می‌ماند: فراخواننده‌ها
    آن را پاس می‌دهند و روزی که پیشنهادها به نامِ مشتری اشاره کنند لازم می‌شود.
    """
    if not tools_used:
        return []

    out = []
    seen = set()

    def add(question):
        if len(out) >= MAX_SUGGESTIONS or question in seen:
            return
        seen.add(question)
        out.append(question)

    known = False
    for name in reversed(tools_used):
        questions = FOLLOW_UPS.get(name)
        if not questions:
            continue
        known = True
        for question in questions:
            add(question)

    # ابزارِ ناشناخته — پیشنهادی نمی‌سازیم، چون نمی‌دانیم گفتگو دربارهٔ چه بود
    if not known:
        return []

    for question in GENERAL:
        add(question)

    # اگر با همهٔ این‌ها هم به کف نرسیدیم، چیزی نشان نمی‌دهیم
    return out if len(out) >= MIN_SUGGESTIONS else []
