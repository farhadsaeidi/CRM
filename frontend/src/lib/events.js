// چرا رویداد و نه پراپ؟ فرستنده و گیرنده در دو شاخهٔ جدا از درختِ کامپوننت‌ها
// نشسته‌اند: هدر و فوتر در `RootLayout`اند و صفحه‌ها فرزندِ `Outlet`. رساندنِ
// callback از این مسیر یعنی `RootLayout` باید state هر صفحه را بشناسد.
//
// نامِ رویدادها اینجا جمع‌اند تا رشتهٔ تکراری در دو فایل از هم واگرا نشود.
// (نامِ `crm:transaction-search` عمداً کنارِ خودِ فوتر مانده، چون همان‌جا هم
// صادر می‌شود و جابه‌جا کردنش دو محلِ حقیقت می‌ساخت.)

// مودالِ «ثبت مشتری جدید» در RootLayout است ولی فهرستِ مشتریان در صفحهٔ خودش؛
// بعد از ثبتِ موفق باید فهرست و شاخص‌ها تازه شوند.
export const CUSTOMER_CREATED_EVENT = "crm:customer-created";

// هر جای برنامه می‌تواند مودالِ ثبتِ مشتری را باز کند (مثلاً حالتِ خالیِ داشبورد).
// خودِ مودال در RootLayout است و دکمهٔ هدر — که همسایه‌اش است — با پراپ صدایش
// می‌زند؛ این رویداد برای فراخوان‌های دورتر است.
export const OPEN_NEW_CUSTOMER_EVENT = "crm:open-new-customer";

// راهنمای نرم‌افزار از منوی فوتر باز می‌شود ولی خودِ مودال در RootLayout است،
// چون باید روی هر صفحه‌ای که کاربر هست بیاید.
export const OPEN_GUIDE_EVENT = "crm:open-guide";

// نامِ کسب‌وکار فقط بارِ اول پرسیده می‌شود — موقعِ ارسالِ پیامکِ یادآوری. مودالش
// هم مثلِ بقیه در RootLayout است تا از هر صفحه‌ای باز شود.
export const OPEN_BUSINESS_NAME_EVENT = "crm:open-business-name";

// مودالِ انتخابِ بدهکاران هم از منوی فوتر باز می‌شود و هم بلافاصله بعد از ذخیرهٔ
// نامِ کسب‌وکار — کاربری که برای ارسالِ پیامک آمده بود نباید دوباره از منو شروع کند.
export const OPEN_DEBT_REMINDER_EVENT = "crm:open-debt-reminder";
