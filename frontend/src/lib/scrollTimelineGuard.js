// ⚠️ این ماژول باید پیش از هر ایمپورتی از overlayscrollbars ارزیابی شود.
//
// چرا: overlayscrollbars 2.16.0 (آخرین نسخه) اگر `window.ScrollTimeline` را
// ببیند، حرکتِ دستهٔ اسکرول را با یک انیمیشنِ Web Animations اداره می‌کند و
// `--os-scroll-percent` را اصلاً نمی‌نویسد. آن انیمیشن هنگام بازساختِ
// اسکرول‌بارها cancel می‌شود ولی چون کی‌فریم‌های کش‌شده عوض نشده‌اند دوباره ساخته
// نمی‌شود (خطِ ۱۷۵۹ کتابخانه: تابعِ لغو داخلِ فهرستِ تخریب گذاشته می‌شود، ولی
// کشِ کی‌فریم پاک نمی‌شود). نتیجه: دسته روی translateY(0) — بالای ناحیه — قفل
// می‌شود و با اسکرول تکان نمی‌خورد. بازساخت با ResizeObserver و MutationObserver
// هم رخ می‌دهد، پس از بیرون نمی‌شود جلویش را گرفت.
//
// مسیرِ دومِ کتابخانه (نوشتنِ `--os-scroll-percent` و اجازه دادن به CSS) این
// نقص را ندارد و آزموده شد: با pct برابر ۰ و ۰.۶ و ۱، دسته دقیقاً به اندازهٔ
// (ارتفاعِ ریل − ارتفاعِ دسته) جابه‌جا می‌شود.
//
// کتابخانه این API را فقط یک بار و در لحظهٔ ارزیابیِ ماژول می‌خواند، پس همین‌جا
// کنار گذاشته می‌شود. در `main.jsx` بلافاصله برگردانده می‌شود تا بقیهٔ صفحه
// دسترسی‌اش را از دست ندهد.
//
// یک نسخهٔ دیگر از همین محافظ در `index.html` هم هست تا اگر روزی ترتیبِ
// ایمپورت‌ها به‌هم خورد باز هم کار کند. هر دو idempotent‌اند.
if (typeof window !== "undefined" && window.ScrollTimeline) {
    window.__ScrollTimeline = window.ScrollTimeline;
    delete window.ScrollTimeline;
}
